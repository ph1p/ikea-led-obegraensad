void CirclePlugin::setup()
{
  this->circleStep = 0;
}

void CirclePlugin::loop()
{
  if (!timer.isReady(200))
    return;

  Screen.drawBitmap(0, 0, frames[this->circleStep], sizeof(frames[0]), COLS);

  this->circleStep++;
  if (this->circleStep > 14)
  {
    this->circleStep = 7;
  }
}

const char *CirclePlugin::getName() const
{
  return "Circle";
}
